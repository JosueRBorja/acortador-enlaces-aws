"""Fija dependencias base instaladas; ejecutar en un entorno ya validado.

Se omiten extras opcionales de Uvicorn (aceleradores específicos de plataforma).
La instalación resultante funciona con Python estándar tanto en Windows como en Linux.
"""

from importlib.metadata import distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def main() -> None:
    pending = ["fastapi", "uvicorn", "boto3", "pydantic-settings"]
    versions: dict[str, str] = {}
    while pending:
        name = canonicalize_name(pending.pop())
        if name in versions:
            continue
        package = distribution(name)
        versions[name] = package.version
        for raw in package.requires or []:
            requirement = Requirement(raw)
            if requirement.marker is None or requirement.marker.evaluate({"extra": ""}):
                pending.append(requirement.name)
    lines = ["# Generated by scripts/lock_dependencies.py; base runtime dependencies only."]
    lines.extend(f"{name}=={version}" for name, version in sorted(versions.items()))
    target = Path(__file__).resolve().parents[1] / "requirements.lock.txt"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Locked {len(versions)} runtime packages.")


if __name__ == "__main__":
    main()
